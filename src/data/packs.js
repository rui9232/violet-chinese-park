export function packToGame(grade, type) {
  const arcade = ["mole", "dash", "balloon"];
  const pack = BUILTIN_PACKS[grade]?.[type] || (arcade.includes(type) ? BUILTIN_PACKS[grade]?.mole : null);
  if (!pack) return null;
  if (type === "match" || type === "memory" || type === "roots") {
    return {
      type,
      title: `${grade}年級練習`,
      pairs: pack.map(([left, right]) => ({ left, right })),
    };
  }
  return { type, title: `${grade}年級練習`, items: pack };
}
